    c.add('<path d="M33 27 C 29 41, 29 60, 33 74 C 40 78, 60 78, 67 74 '
          'C 71 60, 71 41, 67 27"/>')
    c.add('<ellipse cx="50" cy="24" rx="19" ry="6.5"/>')
    c.add('</g>')
    c.add('<g transform="translate(58 12) rotate(-12)" stroke-width="3">')
