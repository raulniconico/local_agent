def sessions():
    """+1: every brew session across every bean, sorted by date (newest
    first) -- the chronological counterpart to Home's per-bean grouping.

    Reuses bean_detail_lower's own session-row convention (wireframes.py:
    date, method, dose, score and an extraction word on one compact line, a
    hairline divider, no card chrome) rather than -1_can_drink/Home's card
    treatment: a log is denser and more numerous than a shelf of beans or
    products, and card chrome per row would fight that density.

    Session counts per bean here match home()'s sample brew_count values
    (Ethiopia 4, Colombia 2, Guatemala 1, Kenya 0) so the two pages agree.

    The leading circle is the dripper, not the bean: bean identity is
    already fully spelled out as the row's own title text, so a second,
    abbreviated repeat of it (initials in a monogram) would be redundant.
    Method is the thing the title text *doesn't* already say, and the one a
    dripper_icons/ figure (see dripper_icon() above) actually helps to
    scan for -- "V60" only means something to someone who already knows
    what a V60 looks like, and several rows in a row using the same
    dripper become a recognisable silhouette repeating, not five separate
    words to re-read. The circle itself switches from the old monogram's
    pale secondaryContainer to BRAND: the icon is white-only linework
    (dripper_icon()'s own recipe), and secondaryContainer is pale enough
    that white on it is close to invisible -- BRAND is the same green
    can_boy()/bag_tile() already stand their own white linework on.
    """
    log = [
        ("30 Jul", "Ethiopia Guji Natural", "V60", "15.0 g", 4.5, "well extracted"),
        ("25 Jul", "Ethiopia Guji Natural", "Kalita", "16.0 g", 4.0, "slightly under"),
        ("22 Jul", "Colombia Huila Washed", "V60", "15.5 g", 3.5, "slightly over"),
        ("18 Jul", "Ethiopia Guji Natural", "V60", "15.0 g", 4.0, "well extracted"),
        ("15 Jul", "Guatemala Huehue", "V60", "15.0 g", 3.0, "slightly under"),
        ("12 Jul", "Ethiopia Guji Natural", "Chemex", "20.0 g", 4.5, "well extracted"),
        ("08 Jul", "Colombia Huila Washed", "Kalita", "16.0 g", 4.0, "well extracted"),
    ]
    c = wf.Canvas("Sessions — scheme E")
    wf.status_bar(c)
    wf.top_bar(c, "Sessions", back=True, actions=("sort",))
    wf.text(c, 20, 112, f"Newest first · {len(log)} sessions", "labelMedium",
            wf.C["onSurfaceVariant"])

    row_h, row_gap, y0 = 64, 4, 132
    for i, (date, bean, dripper, dose, score, note) in enumerate(log):
        ry = y0 + i * (row_h + row_gap)
        # BRAND, not secondaryContainer: the icons are white-only linework
        # (dripper_icon()/can_boy()/bag_tile()'s shared recipe), and
        # secondaryContainer (#E3F6E3) is pale enough that white on it is
        # nearly invisible -- the same green can_boy/bag_tile stand on
        wf.circle(c, wf.GUTTER + 20, ry + 24, 20, BRAND)
        if not dripper_icon(c, wf.GUTTER + 20, ry + 24, 26, dripper):
            wf.text(c, wf.GUTTER + 20, ry + 29, dripper[:2].upper(), "titleSmall",
                    "#FFFFFF", "middle")
        tx = wf.GUTTER + 52
        wf.text(c, tx, ry + 20, bean, "titleMedium", size=14)
        wf.text(c, W - wf.GUTTER - 24, ry + 20, date, "bodyMedium",
                wf.C["onSurfaceVariant"], "end", size=12)
        wf.text(c, tx, ry + 40, f"{dripper} · {dose} · {score:.1f} · {note}",
                "bodyMedium", wf.C["onSurfaceVariant"], size=12)
        wf.path(c, f"M{W-wf.GUTTER-14} {ry+19} l5 5 l-5 5", stroke=wf.C["outline"], sw=1.6)
        if i < len(log) - 1:
            wf.line(c, tx, ry + row_h - 8, W - wf.GUTTER, ry + row_h - 8)

